// Package semver checks version strings against Semantic Versioning 2.0.0.
package semver

import "regexp"

// pattern is the regular expression recommended by semver.org. It matches what
// Elixir's Version.parse/1 accepts, which is what NervesHub uses to validate
// archive versions: MAJOR.MINOR.PATCH with no leading zeros and no "v"
// prefix, then an optional -prerelease (numeric identifiers without leading
// zeros) and +build.
var pattern = regexp.MustCompile(`^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)` +
	`(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?` +
	`(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$`)

// Valid reports whether v is a valid SemVer 2.0.0 version.
func Valid(v string) bool {
	return pattern.MatchString(v)
}
